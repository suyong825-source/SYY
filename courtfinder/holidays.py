def holiday_name(date: dt.date | str) -> str:
    key = date if isinstance(date, str) else date.isoformat()
    return KR_HOLIDAYS.get(key, "")


def is_holiday(date: dt.date | str) -> bool:
    return bool(holiday_name(date))


def is_rest_day(date: dt.date) -> bool:
    """코트가 '주말·공휴일' 일정으로 도는 날인지."""
    return date.weekday() >= 5 or is_holiday(date)


def covered_years() -> list[int]:
    return sorted({int(k[:4]) for k in KR_HOLIDAYS})
